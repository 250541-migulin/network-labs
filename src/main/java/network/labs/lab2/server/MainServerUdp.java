package network.labs.lab2.server;

import network.labs.lab2.common.Config;

/**
 * Точка входа UDP-сервера для лабораторной работы №2.
 *
 * Класс выполняет минимальную инициализацию и передаёт управление
 * основному компоненту {@link UdpServer}. Все параметры (порт, пути,
 * сетевые настройки) вынесены в {@link Config} для централизованного
 * управления и соответствия требованию кроссплатформенности.
 *
 * @see UdpServer
 * @see Config
 */
public class MainServerUdp {

    /**
     * Основной метод приложения.
     *
     * Алгоритм работы:
     * 1. Выводит заголовок и номер порта для информирования оператора.
     * 2. Создаёт экземпляр {@code UdpServer} с портом из конфигурации.
     * 3. Запускает основной цикл обработки команд через {@code start()}.
     * 4. При возникновении неустранимой ошибки (например, порт занят,
     *    нет прав на привязку):
     *    - выводит сообщение об ошибке в stderr,
     *    - печатает стек-трейс для отладки,
     *    - завершает процесс с кодом 1 (ошибка).
     *
     * Метод не возвращает управление при успешном запуске, так как
     * {@code UdpServer.start()} работает в бесконечном цикле.
     *
     * @param args аргументы командной строки (не используются,
     *             все параметры задаются в {@link Config})
     */
    public static void main(String[] args) {
        System.out.println("=== Запуск UDP-сервера ЛР-2 ===");
        System.out.println("Порт: " + Config.PORT);

        try {
            // Инициализация и запуск сервера
            // Все настройки (буферы, таймауты, пути) берутся из Config
            new UdpServer(Config.PORT).start();
        } catch (Exception e) {
            // Обработка неустранимых ошибок инициализации:
            // - порт уже занят другим процессом
            // - недостаточно прав для привязки к порту (<1024 без root)
            // - ошибка создания сокета
            System.err.println("Ошибка запуска сервера: " + e.getMessage());
            e.printStackTrace();
            // Код завершения 1 сигнализирует об ошибке для скриптов/мониторинга
            System.exit(1);
        }
    }
}