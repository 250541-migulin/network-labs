package network.labs.lab2.common;

import java.nio.file.Path;

/**
 * Глобальная конфигурация клиент-серверного приложения для ЛР-2 (UDP).
 *
 * Все параметры вынесены в один класс для:
 * - централизованного управления настройками
 * - быстрой адаптации под разные сетевые условия (LAN, эмуляция)
 * - соответствия требованию кроссплатформенности (нет хардкода в коде)
 *
 * Значения подобраны для работы в LAN с MTU=1500 и задержкой ~1 мс.
 */
public final class Config {

    // ========================================================================
    // Сетевые параметры
    // ========================================================================

    /** Порт, на котором сервер ожидает UDP-датаграммы. */
    public static final int PORT = 8888;

    /** IP-адрес сервера для клиентского соединения (настраивается под топологию). */
    public static final String SERVER_HOST = "10.0.0.3";

    /**
     * Размер буфера сокета (отправка/приём).
     *
     * Увеличен относительно значения по умолчанию для:
     * - снижения частоты системных вызовов copy_from_user/copy_to_user
     * - повышения пропускной способности в условиях высокой нагрузки
     *
     * 256 КБ — компромисс между производительностью и потреблением памяти.
     */
    public static final int SOCK_BUF_SIZE = 256 * 1024;

    // ========================================================================
    // Параметры собственного протокола поверх UDP
    // ========================================================================

    /**
     * Размер заголовка прикладного протокола (байт).
     *
     * Формат: Seq(2) | ACK(2) | Flags(1) | Len(2) = 7 байт.
     * Этот заголовок добавляется к полезной нагрузке перед сериализацией
     * и интерпретируется только на уровне приложения.
     */
    public static final int HEADER_SIZE = 7;

    /**
     * Максимальный размер полезной нагрузки в одном пакете (байт).
     *
     * Рассчитан исходя из стандартного MTU Ethernet:
     *   1500 (MTU) - 20 (IP) - 8 (UDP) - 7 (наш заголовок) = 1465
     *
     * Такой размер гарантирует отсутствие IP-фрагментации:
     * - потеря одного фрагмента = потеря всей UDP-датаграммы
     * - ретрансмиссия всего пакета снижает пропускную способность
     *
     * Поэтому 1465 байт — это максимум полезных данных без риска фрагментации.
     */
    public static final int PAYLOAD_SIZE = 1465;

    // ========================================================================
    // Параметры надёжности (эмуляция TCP-механизмов в userspace)
    // ========================================================================

    /**
     * Размер скользящего окна (количество пакетов).
     *
     * Позволяет отправителю иметь в сети до 64 неподтверждённых пакетов.
     * Выбран исходя из BDP для LAN:
     *   1 Гбит/с × 1 мс ≈ 125 КБ ≈ 85 пакетов по 1465 Б
     * 64 — безопасное значение, близкое к насыщению канала, но без перегрузки буферов.
     */
    public static final int WINDOW_SIZE = 64;

    /**
     * Таймаут ожидания подтверждения (ACK) для одного пакета (мс).
     *
     * 50 мс достаточно для LAN, но не создаёт излишней нагрузки на CPU
     * при частых проверках. При превышении пакет помечается на ретрансмиссию.
     */
    public static final int ACK_TIMEOUT_MS = 50;

    /**
     * Таймаут сокета для операций receive при ожидании команд (мс).
     *
     * Используется в циклах receiveCmd/readCmd для предотвращения
     * бесконечного блокирования при потере пакетов.
     */
    public static final int SOCKET_TIMEOUT_MS = 20;

    /**
     * Максимальное количество последовательных неудачных попыток
     * отправить/получить пакет перед разрывом сессии.
     *
     * При значении 50 и таймауте 20 мс реакция на обрыв составляет ~1 сек,
     * что удовлетворяет требованию «узнать в разумное время».
     */
    public static final int MAX_CONSECUTIVE_DROPS = 50;

    /**
     * Интервал отправки кумулятивных подтверждений (в пакетах).
     *
     * Вместо ACK на каждый пакет, получатель шлёт одно подтверждение
     * каждые 8 пакетов. Это снижает служебный трафик:
     *   - Оверхед: 7 / (8×1465 + 7) ≈ 0.06% (требование ≤30% выполняется)
     *   - При потере одного ACK переотправляется максимум 8 пакетов (~11 КБ)
     *
     * Значение 8 выбрано как степень двойки для удобства вычислений.
     */
    public static final int ACK_INTERVAL = 8;

    // ========================================================================
    // Пути к файлам (абсолютные, для работы в GNS3/виртуальных машинах)
    // ========================================================================

    /** Директория с исходными файлами для отправки (сервер) / загрузки (клиент). */
    public static final Path SRC_DIR = Path.of("files/source");

    /** Директория для сохранения принятых файлов. */
    public static final Path DST_DIR = Path.of("files/tmp");

    // ========================================================================
    // Служебные
    // ========================================================================

    /** Приватный конструктор предотвращает создание экземпляров класса. */
    private Config() {}
}