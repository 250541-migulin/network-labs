package network.labs.lab1.common;

import java.nio.file.Path;
import java.time.format.DateTimeFormatter;

/**
 * Глобальная конфигурация для Лабораторной работы №1 (TCP).
 * Все параметры вынесены сюда для централизованного управления.
 * Код полностью кроссплатформенный: нет условной компиляции, пути и настройки
 * адаптируются под среду выполнения.
 */
public final class Config {

    // ========================================================================
    // Сетевые параметры
    // ========================================================================

    /**
     * IP-адрес сервера.
     * Для локального тестирования: "127.0.0.1"
     * Для GNS3/сети: реальный IP сервера (например, "10.0.0.2")
     */
    public static final String SERVER_HOST = "10.0.0.2";

    /** Порт TCP-сервера. Должен быть открыт в фаерволе и не занят другими сервисами. */
    public static final int SERVER_PORT = 8888;

    /**
     * Таймаут сокета (миллисекунды).
     * Согласно методичке: разрыв соединения должен определяться за 30 сек – 5 мин.
     * 120 000 мс = 2 минуты. Используется в setSoTimeout() для детекта обрыва.
     */
    public static final int SOCKET_TIMEOUT_MS = 120_000;

    // ========================================================================
    // Пути к файлам
    // ========================================================================

    /**
     * Директория с исходными файлами.
     * Server: файлы для отправки (DOWNLOAD).
     * Client: файлы для загрузки (UPLOAD).
     * Path.of() корректно обрабатывает разделители (/ или \) под любой ОС.
     * При необходимости замените на абсолютный путь вашей системы.
     */
    public static final Path SOURCE_DIR = Path.of("/root/files/source");

    /**
     * Директория для сохранения принятых файлов.
     * Server: куда сохраняются загруженные файлы.
     * Client: куда сохраняются скачанные файлы.
     */
    public static final Path TMP_DIR = Path.of("/root/files/tmp");

    /**
     * Формат времени для команды time
     */
    public static final DateTimeFormatter TIME_FORMAT = DateTimeFormatter.ofPattern("HH:mm:ss");
    // ========================================================================
    // Служебные
    // ========================================================================

    /** Приватный конструктор: класс содержит только статические константы. */
    private Config() {}
}