package network.labs.lab1.common;

/**
 * Утилиты для сетевых расчётов.
 * Все методы статические, класс не создаётся в экземплярах.
 */
public final class NetworkUtils {

    // Приватный конструктор предотвращает создание экземпляров
    private NetworkUtils() {
    }

    /**
     * Рассчитывает скорость передачи данных в Мбит/с.
     *
     * Формула: (байты * 8) / (миллисекунды * 1000)
     *
     * Важное примечание: расчёт включает все накладные расходы сессии:
     * - рукопожатие (команды UPLOAD/OK/READY)
     * - ожидание подтверждений (ACK)
     * - системные задержки (I/O, планировщик)
     * Для малых файлов оверхед составляет значительную долю времени,
     * поэтому расчётная скорость ниже. Для больших файлов оверхед
     * "амортизируется" объёмом данных, и скорость приближается к
     * реальной пропускной способности канала.
     *
     * @param bytes количество переданных/принятых полезных байт
     * @param elapsedMs время передачи в миллисекундах
     * @return скорость в Мбит/с (возвращает 0.0, если время <= 0)
     */
    public static double calcSpeedMbps(long bytes, long elapsedMs) {
        if (elapsedMs <= 0) {
            return 0.0;
        }
        return (bytes * 8.0) / (elapsedMs * 1000.0);
    }
}