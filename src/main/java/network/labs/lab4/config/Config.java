package network.labs.lab4.config;

import java.nio.file.Path;
import java.time.format.DateTimeFormatter;

/**
 * Глобальная конфигурация для ЛР-4.
 * Содержит сетевые параметры, таймауты и пути к файлам.
 * Все значения вынесены сюда для быстрой адаптации под среду GNS3.
 * Класс не создаёт экземпляры, только хранит статические константы.
 */
public final class Config {

    // ========================================================================
    // Сетевые параметры
    // ========================================================================

    /**
     * IP-адрес сервера.
     * На виртуальной машине, где запущен сервер, укажите её адрес в сети GNS3.
     */
    public static final String SERVER_HOST = "10.0.0.5";

    /**
     * Порт TCP-сервера.
     */
    public static final int SERVER_PORT = 8888;

    /**
     * Таймаут сокета в миллисекундах.
     * При отсутствии данных в течение этого времени будет сгенерировано
     * SocketTimeoutException. Значение 120 000 мс = 2 минуты соответствует
     * требованию методички (детект обрыва от 30 сек до 5 мин).
     */
    public static final int SOCKET_TIMEOUT_MS = 120_000;

    // ========================================================================
    // Пути к файлам
    // ========================================================================

    /**
     * Директория с файлами для скачивания (команда DOWNLOAD).
     * Сервер читает файлы отсюда.
     */
    public static final Path SOURCE_DIR = Path.of("files/source");

    /**
     * Директория для сохранения загруженных файлов (команда UPLOAD).
     * Сервер пишет файлы сюда.
     */
    public static final Path TMP_DIR = Path.of("files/tmp");

    /**
     * Формат времени, используемый в команде TIME.
     */
    public static final DateTimeFormatter TIME_FORMAT = DateTimeFormatter.ofPattern("HH:mm:ss");

    // ========================================================================
    // Служебные
    // ========================================================================

    /** Приватный конструктор запрещает создание экземпляров класса. */
    private Config() {
        // намеренно оставлен пустым
    }
}