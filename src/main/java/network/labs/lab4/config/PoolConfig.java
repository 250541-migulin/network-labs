package network.labs.lab4.config;

/**
 * Конфигурация пула потоков для сервера ЛР-4, вариант 8.
 * Все параметры вынесены сюда для централизованного управления.
 * Класс содержит только статические константы, экземпляры не создаются.
 */
public final class PoolConfig {

    // ========================================================================
    // Настройки пула потоков (ExecutorService)
    // ========================================================================

    /**
     * Минимальное число потоков в пуле (Nmin).
     * Эти потоки создаются при старте сервера и не завершаются,
     * даже если нет активных подключений.
     */
    public static final int CORE_POOL_SIZE = 3;

    /**
     * Максимальное число потоков в пуле (Nmax).
     * При высокой нагрузке пул может временно расширяться до этого значения.
     * Превышение лимита приведёт к отказу в приёме новых подключений.
     */
    public static final int MAX_POOL_SIZE = 10;

    /**
     * Время жизни простого потока в секундах (keep-alive).
     * Если поток не получает новую задачу в течение этого времени,
     * и общее число потоков больше CORE_POOL_SIZE, он завершается.
     */
    public static final long KEEP_ALIVE_SECONDS = 60L;

    /**
     * Размер очереди задач, когда все потоки пула заняты.
     * Новые подключения будут ставиться в очередь.
     * При переполнении очереди сервер вернёт ошибку подключения.
     */
    public static final int QUEUE_CAPACITY = 50;

    // ========================================================================
    // Служебные
    // ========================================================================

    /** Приватный конструктор: класс содержит только статические константы. */
    private PoolConfig() {
        // намеренно оставлен пустым
    }
}